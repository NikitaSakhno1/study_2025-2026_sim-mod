# # Дискретно-событийная SIR-модель
#
# ## Постановка задачи
#
# В работе реализуется дискретно-событийная стохастическая
# SIR-модель распространения инфекции.
#
# Популяция состоит из трёх групп:
#
# - S — восприимчивые к инфекции;
# - I — инфицированные;
# - R — переболевшие.
#
# Каждый индивид моделируется отдельным процессом.
# События заражения и выздоровления происходят в дискретные
# моменты времени.

using DrWatson

@quickactivate "lab08"

include(srcdir("sir_model.jl"))

using Random
using StatsPlots
using DataFrames

# ## Исходные параметры
#
# Длительность моделирования составляет 40 единиц времени.
# Начальное состояние:
#
# S = 990, I = 10, R = 0.
#
# Параметры модели:
#
# β = 0.05 — вероятность заражения при контакте;
#
# c = 10.0 — средняя частота контактов;
#
# γ = 0.25 — интенсивность выздоровления.

tmax = 40.0

u0 = [990, 10, 0]

p = [0.05, 10.0, 0.25]

# ## Инициализация генератора случайных чисел
#
# Фиксируем зерно генератора случайных чисел для обеспечения
# воспроизводимости результатов.

Random.seed!(1234)

# ## Создание и запуск модели
#
# Создаём модель SIR, активируем процессы всех индивидов
# и запускаем дискретно-событийную симуляцию.

des_model = MakeSIRModel(u0, p)

activate(des_model)

sir_run(des_model, tmax)

# ## Получение результатов
#
# Результаты работы модели преобразуются в таблицу DataFrame.
# Таблица содержит время события и текущие значения S, I и R.

data_des = out(des_model)

data_des

# ## Визуализация результатов
#
# Построим временные ряды численности восприимчивых,
# инфицированных и переболевших.

@df data_des plot(
    :t,
    [:S :I :R],
    labels = ["S" "I" "R"],
    xlab = "Время",
    ylab = "Численность",
    title = "Дискретно-событийная SIR модель"
)

savefig(plotsdir("sir_des_literate.png"))

# ## Вывод
#
# В результате моделирования получены временные ряды
# численности восприимчивых, инфицированных и переболевших.
# Дискретно-событийный подход позволяет моделировать
# распространение инфекции через последовательность
# индивидуальных случайных событий.