# # Дискретно-событийная SIR-модель с набором параметров
#
# В данной версии программы исследуется влияние вероятности
# передачи инфекции β на динамику дискретно-событийной
# SIR-модели.
#
# Рассматриваются три значения β:
#
# β = 0.03, β = 0.05 и β = 0.07.
#
# Остальные параметры модели остаются неизменными.

using DrWatson

@quickactivate "lab08"

include(srcdir("sir_model.jl"))

using Random
using StatsPlots
using DataFrames

# ## Общие параметры

tmax = 40.0

u0 = [990, 10, 0]

# Частота контактов
c = 10.0

# Интенсивность выздоровления
γ = 0.25

# Набор значений вероятности заражения
betas = [0.03, 0.05, 0.07]

# ## Запуск серии экспериментов
#
# Для каждого значения β создаётся отдельная модель.
# Используется одинаковое начальное состояние и одинаковые
# значения c и γ.

results = DataFrame()

for β in betas

    Random.seed!(1234)

    p = [β, c, γ]

    model = MakeSIRModel(u0, p)

    activate(model)

    sir_run(model, tmax)

    data = out(model)

    data[!, :β] .= β

    append!(results, data)

end

# ## Результаты экспериментов

results

# ## Визуализация
#
# Построим графики изменения численности инфицированных
# для разных значений β.

plot(
    xlabel = "Время",
    ylabel = "Численность инфицированных",
    title = "Влияние параметра β на динамику инфекции"
)

for β in betas

    subset = filter(row -> row.β == β, results)

    plot!(
        subset.t,
        subset.I,
        label = "β = $(β)"
    )

end

savefig(
    plotsdir("sir_beta_comparison.png")
)

# ## Сравнение максимального числа инфицированных
#
# Для каждого значения β определим максимальную численность
# инфицированных.

peak_results = DataFrame(
    β = Float64[],
    peak_I = Int64[],
    peak_time = Float64[]
)

for β in betas

    subset = filter(row -> row.β == β, results)

    index = argmax(subset.I)

    push!(
        peak_results,
        (
            β,
            subset.I[index],
            subset.t[index]
        )
    )

end

peak_results

# ## Вывод
#
# При увеличении β вероятность заражения при контакте
# возрастает. Поэтому эпидемия распространяется быстрее,
# а максимальная численность инфицированных, как правило,
# становится выше.
#
# Полученные результаты позволяют сравнить динамику
# дискретно-событийной SIR-модели для разных значений
# вероятности передачи инфекции.